"""检索证据分档（2026-10-28）。

检索完不能直接把资料丢给模型就完事——模型不知道"这批资料到底有多可信"：
命中很硬时它应该严格照着资料答并标编号；命中很差时它还硬凑，就是把猜测说成
事实。所以把召回质量**显式告诉模型**，让它按档位决定怎么答。

三档：

  high —— 证据充足：严格依据资料，每个关键结论带 [n] 编号，不补资料外的东西。
  mid  —— 证据一般：以资料为主，资料没覆盖处可用常识谨慎补充并说明。
  low  —— 证据不足：允许结合自身知识作答，但必须让用户分清哪句是资料、
          哪句是通用知识（拒答在这里被替换成"如实说明着答"——用户要的是答案，
          不是一句"资料里没有"）。

阈值不另起一套：直接复用标定出来的 refusal.min_score（那是"够不够硬"的已知
分界线），mid 取它的 6 折。再单独加两个旋钮只会让人不知道该调哪个。

三档共用一条底线：不许用「资料里没有」收尾。实测过，不给这条底线，模型拿到
一堆不沾边的资料后会推演一圈然后投降——那正是这套分档要消灭的东西。
"""

from __future__ import annotations

GRADES = ("high", "mid", "low")

# 低于 min_score 的 6 折就认为"基本没命中"
_MID_RATIO = 0.6

# 三档共用的一条底线：不许以"资料里没有 / 无法回答"收尾。
# 实测里它就是漏洞——召回一般时模型拿到一堆不沾边的资料，照着"以资料为主"
# 的指令推演一圈，最后憋出一句"无法给出答案"。用户要的是答案，不是投降声明。
_NO_SURRENDER = (
    "无论资料是否够用，都不要只回答「资料里没有」或「无法回答」就结束——"
    "资料里找不到就用自己的知识把问题答完，并标明这部分不是来自资料。"
)

# 系统提示里的"禁止外部知识"是硬约束，小模型只认系统提示。证据不足时不点名
# 作废它，模型就会被按死在"资料中未找到相关依据"上——实测如此。
_OVERRIDE = (
    "\n\n【本轮例外：检索证据不足】上面硬性要求里的第 1、3 条本轮不适用。"
    "这批资料很可能不足以支撑本问题，允许你使用自身知识作答；但必须让用户分得清："
    "来自资料的内容照旧带 [n] 来源编号，来自通用知识的部分明确写"
    "「资料中未找到，以下为通用知识」。仍然禁止编造资料里有的细节。"
)

_GUIDANCE = {
    "high": (
        "【检索证据：充足】上面的资料足以回答这个问题。请严格依据资料作答，"
        "每个关键结论都带上对应的 [n] 来源编号；不要补充资料里没有的内容。"
        f"资料万一真的没覆盖到提问点，也要先用资料里有的内容作答，"
        f"缺失处用自身知识补上并标明来源不同——{_NO_SURRENDER}"
    ),
    "mid": (
        "【检索证据：一般】上面的资料可能与问题只有部分相关，甚至基本无关。"
        "相关的部分照常作答并带 [n] 来源编号；资料没有覆盖到的部分，"
        "以及资料整体与问题无关的情况，直接用自身知识作答，"
        "并明确写「资料中未找到，以下为通用知识」。不要编造资料里有的细节。\n"
        + _NO_SURRENDER
    ),
    "low": (
        "【检索证据：不足】上面的资料很可能不足以支撑这个问题。你可以结合自身知识作答，"
        "但必须让用户分得清：来自资料的内容照旧带 [n] 来源编号；来自通用知识的部分"
        "明确写「资料中未找到，以下为通用知识」。不要编造资料里有的细节，也不要"
        "把通用知识说成来自资料。\n" + _NO_SURRENDER
    ),
}

# 维语只给一行档位标记：整段中文指令会把模型重新拽回中文。底线那句留给维语短句。
_NO_SURRENDER_UG = "مەنبەدە بولمىسا ئۆز بىلىمىڭىز بىلەن جاۋاب بېرىڭ؛ «مەنبەدە يوق» دەپلا توختىماڭ."

_GUIDANCE_UG = {
    "high": "【ئىزدەش ئاساسى: يېتەرلىك】",
    "mid": "【ئىزدەش ئاساسى: ئوتتۇرا】",
    "low": "【ئىزدەش ئاساسى: يېتەرسىز】",
}

_LABEL = {
    "high": {"zh": "依据资料", "ug": "مەنبەگە ئاساسەن", "en": "From sources"},
    "mid": {"zh": "资料为主", "ug": "مەنبە ئاساس قىلىندى", "en": "Mostly from sources"},
    "low": {"zh": "资料不足 · 含通用知识", "ug": "مەنبە يېتەرسىز · ئادەتتىكى بىلىم",
            "en": "Sources thin · general knowledge"},
}


def grade_of(
    top_score: float | None, *, min_score: float, mid_ratio: float = _MID_RATIO
) -> str:
    """按命中分与标定阈值分档。top_score 为 None（一条都没召回）时算最低档。

    mid_ratio 从 evidence.mid_ratio 读（可调参数面板），默认 0.6 是实测折中值。
    """
    if top_score is None:
        return "low"
    if min_score <= 0:
        min_score = 0.3
    ratio = float(mid_ratio) if mid_ratio and mid_ratio > 0 else _MID_RATIO
    if top_score >= min_score:
        return "high"
    if top_score >= min_score * ratio:
        return "mid"
    return "low"


def guidance(grade: str, lang: str = "zh") -> str:
    """给模型的那段指令。维语场景里草稿是中文写的，指令也就用中文下发——
    给维语提示配上中文指令，模型只会两头不靠。"""
    if lang == "ug" and grade in _GUIDANCE_UG:
        # 维语直接作答（direct 模式）时，只用一行档位标记，避免超长中文指令
        # 把模型重新拽回中文。
        return f"{_GUIDANCE_UG[grade]} {_NO_SURRENDER_UG}"
    return _GUIDANCE.get(grade, _GUIDANCE["mid"])


def override(grade: str) -> str:
    """追加到系统提示词后面的"本轮例外"条款。

    必须走系统提示，不能只写在用户消息里：qa_v1 里那条
    "禁止使用任何外部知识、常识或推测补充"是硬约束，小模型会认系统提示不认
    后面追加的用户消息——实测就是它把模型按死在"资料中未找到相关依据"上。
    所以证据不足时，得明确点名作废那一条。
    """
    if grade == "high":
        return ""
    return _OVERRIDE


def label(grade: str, lang: str = "zh") -> str:
    """界面上给用户看的标签——"这个答案有多少是资料里的"必须一眼可见。"""
    return _LABEL.get(grade, _LABEL["mid"]).get(lang, _LABEL[grade]["zh"])
