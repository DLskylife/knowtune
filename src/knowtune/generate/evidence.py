"""检索证据分档（2026-10-28，2026-11-06 改口径）。

检索完不能直接把资料丢给模型就完事——模型不知道"这批资料到底有多可信"：
命中很硬时它该照着资料答并标编号；命中很差时它还硬凑，就是把猜测说成事实。
所以把召回质量**显式告诉模型**，让它按档位决定怎么答。

口径变过一次，别按老注释理解：以前 low 档的兜底是"允许用自身知识，但要明写
『资料中未找到，以下为通用知识』"。用户实测反馈是——满屏「资料中未找到」
「资料中提到」「资料显示」，答案短得像检索报告。现在改成：

  * 资料答到了 → 带 [n]，照资料说；
  * 资料没答到 / 只答了一半 / 讲的是另一个病 → **用自身知识把问题完整答完**，
    不带编号即可，不要求写任何"资料里没有"的说明；
  * 带 [n] 与不带 [n] 就是来源分界，界面上另有徽标，不必在正文里反复声明。

档位只管"这批资料能不能信"，不管"写出来像不像人话"；后者由末尾那句
【怎么写】负责。风格条款放在生成前最后一行，是实测最有效的位置。

阈值不另起一套：直接复用标定出来的 refusal.min_score（那是"够不够硬"的已知
分界线），mid 取它的 6 折。
"""

from __future__ import annotations

GRADES = ("high", "mid", "low")

# 低于 min_score 的 6 折就认为"基本没命中"
_MID_RATIO = 0.6

# 三档共用的一条底线：不许以"资料里没有 / 无法回答"收尾，也不许把答案写成
# 一份检索报告。实测里这就是漏洞——召回一般时模型拿到一堆不沾边的资料，
# 推演一圈后投降，或者干脆复述"资料里讲了什么"就算答完。
_NO_SURRENDER = (
    "资料没有答到的部分，必须用自身知识把这个问题**完整答完**；"
    "不许只回一句「资料里没有」「无法回答」，也不许把答案写成一篇"
    "「资料中显示……资料中未找到……」的检索报告。"
)

# 系统提示层的一句补充。qa_v1 已经不再禁止外部知识，所以这里不再"点名作废
