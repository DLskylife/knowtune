        "«ماتېرىيالغا ئاساسلانغاندا» «قىسقىسى» بىلەن باشلىماڭ ياكى ئاخىرلاشتۇرماڭ؛ "
        "ئاخىرىدا پەقەت شۇ ماتېرىيالدا راستتىنلا تىلغا ئېلىنغان چەكلىمىنىلا يېزىڭ، "
        "يوق بولسا ئەمەلىي مەزمۇندا توختاڭ. ئەگەر ماتېرىيالدا سۆزلەنگەن كېسەل باشقا بولسا: "
        "ئاۋۋال «ماتېرىيالدا بۇ كېسەلنىڭ خاتىرىسى يوق» دەپ بىر جۈملە يېزىڭ، "
