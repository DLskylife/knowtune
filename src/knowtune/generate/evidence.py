"""检索证据分档（2026-10-28）。

检索完不能直接把资料丢给模型就完事——模型不知道"这批资料到底有多可信"：
命中很硬时它应该严格照着资料答并标编号；命中很差时它还硬凑，就是把猜测说成
事实。所以把召回质量**显式告诉模型**，让它按档位决定怎么答。

三档：

  high —— 证据充足：严格依据资料，每个关键结论带 [n] 编号，不补资料外的东西。
  mid  —— 证据一般：以资料为主，资料没覆盖处可用常识谨慎补充并说明。
  low  —— 证据不足：允许结合自身知识作答，但必须让用户分清哪句是资料、
          哪句是通用知识（拒答在这里被替换成"如实说明着答"——用户要的是答案，
          不是一句"资料里没有"）。

阈值不另起一套：直接复用标定出来的 refusal.min_score（那是"够不够硬"的已知
分界线），mid 取它的 6 折。再单独加两个旋钮只会让人不知道该调哪个。

三档共用一条底线：不许用「资料里没有」收尾。实测过，不给这条底线，模型拿到
一堆不沾边的资料后会推演一圈然后投降——那正是这套分档要消灭的东西。
"""

from __future__ import annotations

GRADES = ("high", "mid", "low")

# 低于 min_score 的 6 折就认为"基本没命中"
_MID_RATIO = 0.6

# 三档共用的一条底线：不许以"资料里没有 / 无法回答"收尾。
# 实测里它就是漏洞——召回一般时模型拿到一堆不沾边的资料，照着"以资料为主"
# 的指令推演一圈，最后憋出一句"无法给出答案"。用户要的是答案，不是投降声明。
_NO_SURRENDER = (
    "无论资料是否够用，都不要只回答「资料里没有」或「无法回答」就结束——"
    "资料里找不到就用自己的知识把问题答完，并标明这部分不是来自资料。"
)

# 系统提示里的"禁止外部知识"是硬约束，小模型只认系统提示。证据不足时不点名
# 作废它，模型就会被按死在"资料中未找到相关依据"上——实测如此。
_OVERRIDE = (
    "\n\n【本轮例外：检索证据不足】上面硬性要求里的第 1、3 条本轮不适用。"
    "这批资料很可能不足以支撑本问题，允许你使用自身知识作答；但必须让用户分得清："
    "来自资料的内容照旧带 [n] 来源编号，来自通用知识的部分明确写"
    "「资料中未找到，以下为通用知识」。仍然禁止编造资料里有的细节。"
)

_GUIDANCE = {
    # high 档的措辞改过（2026-11-06）。原来写的是"上面的资料足以回答这个问题"，
    # 这是一句**系统替模型下的结论**，而它常常是错的：余弦分高只说明字面相关
    # （问"贫血"命中"血液质数量过盛而浓稠"），不是同一个病。模型被这句话逼着
    # 承认"资料够了"，就只能用"可能""推测"把两个病缝在一起，再拿一堆药名填满
    # 模板——截图里那种满篇对冲、句句像填空的答案就是这么来的。
    # 现在只说"命中较强"，把"是否对题"交回给模型判断，并要求它给结论而不是缝合。
    "high": (
        "【检索证据：命中较强】上面的段落与问题的字面相关度较高，但**相关不等于对题**："
        "先看清楚它们讲的是不是同一个病、同一件事。"
        "是同一个问题 → 严格依据资料作答，每个关键结论都带上对应的 [n] 来源编号，"
        "不补充资料里没有的内容。"
        "只是字面相近（例如问「贫血」、资料讲的是「血液质数量过盛而浓稠」）→ "
        "直接说明「资料中没有针对这个病的记载」，再讲清资料里相近的是什么、差在哪里；"
        "**不要用「可能」「推测」把两者缝成一段答案**——缝合出来的答案读起来很顺，"
        "但它既不是资料说的，也不是你判断的。\n"
        + _NO_SURRENDER
    ),
    "mid": (
        "【检索证据：一般】上面的资料可能与问题只有部分相关，甚至基本无关。"
        "相关的部分照常作答并带 [n] 来源编号；资料没有覆盖到的部分，"
        "以及资料整体与问题无关的情况，直接用自身知识作答，"
        "并明确写「资料中未找到，以下为通用知识」。不要编造资料里有的细节。\n"
        + _NO_SURRENDER
    ),
    "low": (
        "【检索证据：不足】上面的资料很可能不足以支撑这个问题。你可以结合自身知识作答，"
        "但必须让用户分得清：来自资料的内容照旧带 [n] 来源编号；来自通用知识的部分"
        "明确写「资料中未找到，以下为通用知识」。不要编造资料里有的细节，也不要"
        "把通用知识说成来自资料。\n" + _NO_SURRENDER
    ),
}

# 维语只给一行档位标记：整段中文指令会把模型重新拽回中文。底线那句留给维语短句。
_NO_SURRENDER_UG = "مەنبەدە بولمىسا ئۆز بىلىمىڭىز بىلەن جاۋاب بېرىڭ؛ «مەنبەدە يوق» دەپلا توختىماڭ."

_GUIDANCE_UG = {
    "high": "【ئىزدەش ئاساسى: يېتەرلىك】",
    "mid": "【ئىزدەش ئاساسى: ئوتتۇرا】",
    "low": "【ئىزدەش ئاساسى: يېتەرسىز】",
}

# 「怎么写」的一句话，永远排在**最后**。
#
# 为什么单独抽出来、而不是塞进 qa_v1.md 里：模型对"离生成最近的那句话"最敏感。
# 系统提示里的风格条款要和一堆硬性要求抢注意力，实测经常抢不过——明明写着
# 不要"综上所述"，它照样收一段"综上所述"。这句话跟在【资料】【问题】后面，
# 是模型张嘴前读到的最后一行，实测能把"根据资料开头 + 综上所述收尾 + 通篇对冲"
# 这三件套一起按住（A/B 见 2026-11-06 的提交说明）。
#
# 档位指令与这句分开维护：前者说"这批资料能不能信"，后者说"写出来像不像人话"。
# 两者会一起变化（证据不足时更不能缝合），但改一个不该顺手动另一个。
